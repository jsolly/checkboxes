#!/usr/bin/env node
/**
 * Writes src/release-id.ts with the current git commit SHA (12-char) for HTML meta.
 * Response header x-release-id is set by Edge Middleware (VERCEL_GIT_COMMIT_SHA) —
 * do not stamp vercel.json; Vercel serves committed headers as-is.
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function run(cmd) {
	try {
		return execSync(cmd, {
			encoding: "utf8",
			stdio: ["ignore", "pipe", "ignore"],
			cwd: repoRoot,
		}).trim();
	} catch {
		return "";
	}
}

const fromEnv =
	process.env.VERCEL_GIT_COMMIT_SHA || process.env.GITHUB_SHA || "";
const sha = fromEnv || run("git rev-parse HEAD");
let releaseId = sha ? sha.slice(0, 12) : "dev";
if (sha && !fromEnv) {
	const dirty = run("git status --porcelain -uno");
	if (dirty) releaseId += "-dirty";
}

writeFileSync(
	resolve(repoRoot, "src/release-id.ts"),
	`// Generated by scripts/gen-release-id.mjs — do not commit the generated version.\nexport const RELEASE_ID = ${JSON.stringify(releaseId)};\n`,
);
process.stdout.write(`release-id: ${releaseId}\n`);
