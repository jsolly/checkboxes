#!/usr/bin/env node
/**
 * Build-time release id for static Vercel sites.
 * Stamps x-release-id into vercel.json headers and writes src/release-id.ts.
 * SHA: VERCEL_GIT_COMMIT_SHA → GITHUB_SHA → git rev-parse HEAD → "dev"
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function run(cmd) {
	try {
		return execSync(cmd, {
			encoding: "utf8",
			stdio: ["ignore", "pipe", "ignore"],
			cwd: repoRoot,
		}).trim();
	} catch {
		return "";
	}
}

const fromEnv =
	process.env.VERCEL_GIT_COMMIT_SHA || process.env.GITHUB_SHA || "";
const sha = fromEnv || run("git rev-parse HEAD");
let releaseId = sha ? sha.slice(0, 12) : "dev";
if (sha && !fromEnv) {
	const dirty = run("git status --porcelain -uno");
	if (dirty) releaseId += "-dirty";
}

const modulePath = resolve(repoRoot, "src/release-id.ts");
writeFileSync(
	modulePath,
	`// Generated by scripts/gen-release-id.mjs — do not commit the generated version.\nexport const RELEASE_ID = ${JSON.stringify(releaseId)};\n`,
);

const vercelPath = resolve(repoRoot, "vercel.json");
const config = JSON.parse(readFileSync(vercelPath, "utf8"));
if (!Array.isArray(config.headers)) config.headers = [];
let catchAll = config.headers.find((h) => h.source === "/(.*)");
if (!catchAll) {
	catchAll = { source: "/(.*)", headers: [] };
	config.headers.push(catchAll);
}
if (!Array.isArray(catchAll.headers)) catchAll.headers = [];
const existing = catchAll.headers.find(
	(h) => String(h.key).toLowerCase() === "x-release-id",
);
if (existing) {
	existing.value = releaseId;
} else {
	catchAll.headers.push({ key: "x-release-id", value: releaseId });
}
writeFileSync(vercelPath, `${JSON.stringify(config, null, "\t")}\n`);
process.stdout.write(`release-id: ${releaseId}\n`);
